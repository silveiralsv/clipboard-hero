import AppKit
import CryptoKit

struct ClipItem: Codable, Identifiable {
    enum Kind: String, Codable { case text, image }

    let id: UUID
    let kind: Kind
    let text: String?  // set for .text items
    let hash: String   // SHA256 of the content; images live at images/<hash>.png
    var date: Date

    /// One-line label for menus and lists.
    var title: String {
        guard let text else { return "Image" }
        let line = text.prefix(200).split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return line.count > 50 ? line.prefix(50) + "…" : line
    }
}

/// Watches the pasteboard and keeps the history (newest first) on disk.
@MainActor
final class ClipboardStore {
    private(set) var items: [ClipItem] = []
    var limit = 500

    private let pasteboard: NSPasteboard
    private let historyURL: URL
    private let imagesURL: URL
    private var changeCount: Int
    private var timer: Timer?
    private let thumbnails = NSCache<NSString, NSImage>()

    // Markers that password managers and similar apps set so their data is not recorded (nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init(directory: URL = URL.applicationSupportDirectory.appending(path: "ClipboardHero"),
         pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        historyURL = directory.appending(path: "history.json")
        imagesURL = directory.appending(path: "images")
        changeCount = pasteboard.changeCount
        try? FileManager.default.createDirectory(at: imagesURL, withIntermediateDirectories: true)
        load()
    }

    /// macOS has no "pasteboard changed" event, so poll the change counter (an integer read, ~free).
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        guard Set(pasteboard.types ?? []).isDisjoint(with: Self.ignoredTypes) else { return }

        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(.text, text: text, data: Data(text.utf8))
        } else if let png = pngData() {
            add(.image, text: nil, data: png)
        }
    }

    func imageURL(for item: ClipItem) -> URL {
        imagesURL.appending(path: "\(item.hash).png")
    }

    /// Puts an item back on the pasteboard with the same bytes, so the watcher moves it to the top instead of duplicating it.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text: pasteboard.setString(item.text ?? "", forType: .string)
        case .image: if let png = try? Data(contentsOf: imageURL(for: item)) { pasteboard.setData(png, forType: .png) }
        }
    }

    /// Downsampled image for menus and lists. `size` is the longest side in points, rendered at 2x for Retina.
    func thumbnail(for item: ClipItem, size: CGFloat) -> NSImage? {
        let key = "\(item.hash)-\(size)" as NSString
        if let cached = thumbnails.object(forKey: key) { return cached }

        let options = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: size * 2,
        ] as CFDictionary
        guard let source = CGImageSourceCreateWithURL(imageURL(for: item) as CFURL, nil),
              let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options) else { return nil }

        let image = NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width / 2, height: cgImage.height / 2))
        thumbnails.setObject(image, forKey: key)
        return image
    }

    private func pngData() -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    private func add(_ kind: ClipItem.Kind, text: String?, data: Data) {
        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()

        if let index = items.firstIndex(where: { $0.hash == hash }) {
            var item = items.remove(at: index)
            item.date = .now
            items.insert(item, at: 0)
        } else {
            let item = ClipItem(id: UUID(), kind: kind, text: text, hash: hash, date: .now)
            if kind == .image {
                do { try data.write(to: imageURL(for: item)) } catch { return }
            }
            items.insert(item, at: 0)
        }

        for item in items.dropFirst(limit) where item.kind == .image {
            try? FileManager.default.removeItem(at: imageURL(for: item))
        }
        items = Array(items.prefix(limit))
        save()
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyURL) else { return }
        do {
            items = try JSONDecoder().decode([ClipItem].self, from: data)
        } catch {
            // Set the unreadable file aside so the next save does not overwrite it.
            let backup = historyURL.deletingLastPathComponent()
                .appending(path: "history-\(Int(Date.now.timeIntervalSince1970)).json.bak")
            try? FileManager.default.moveItem(at: historyURL, to: backup)
        }
    }

    private func save() {
        // ponytail: rewrites the whole file on every copy; fine for ~500 items, move to SQLite if history grows to thousands.
        try? JSONEncoder().encode(items).write(to: historyURL, options: .atomic)
    }
}
